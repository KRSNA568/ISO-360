/**
 * Prerenders public content pages (Annex A library, blog) into static HTML so
 * search engines and no-JS visitors get the full content, page-specific
 * <title>/meta/canonical and JSON-LD. Runs after `vite build`.
 *
 *   1. Builds src/entry-server.jsx for Node (vite SSR build → dist-ssr/)
 *   2. For each route from contentRoutes(), renders it and writes
 *      dist/<path>.html (Cloudflare Pages serves /a/b from /a/b.html)
 *   3. Appends the routes to dist/sitemap.xml
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import { build } from 'vite'

const ROOT     = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DIST     = path.join(ROOT, 'dist')
const SSR_OUT  = path.join(ROOT, 'dist-ssr')
const SITE_URL = 'https://27001certified.in'
const SITE_NAME = '27001certified'

const esc = (s) => String(s)
  .replace(/&/g, '&amp;').replace(/"/g, '&quot;')
  .replace(/</g, '&lt;').replace(/>/g, '&gt;')

function setMeta(html, attr, key, value) {
  const re = new RegExp(`(<meta\\s+${attr}="${key}"\\s+content=")[^"]*(")`)
  if (!re.test(html)) {throw new Error(`template is missing <meta ${attr}="${key}">`)}
  return html.replace(re, `$1${esc(value)}$2`)
}

function jsonLd(route) {
  const url = `${SITE_URL}${route.path}`
  const graph = [
    {
      '@type': 'BreadcrumbList',
      itemListElement: route.breadcrumbs.map((b, i) => ({
        '@type': 'ListItem', position: i + 1, name: b.name, item: `${SITE_URL}${b.path}`,
      })),
    },
    route.type === 'article'
      ? {
          '@type': 'Article', headline: route.title, description: route.description, url,
          inLanguage: 'en', publisher: { '@type': 'Organization', name: SITE_NAME, url: SITE_URL },
        }
      : { '@type': 'CollectionPage', name: route.title, description: route.description, url },
  ]
  // Escape "<" so content can never close the script tag
  const json = JSON.stringify({ '@context': 'https://schema.org', '@graph': graph }).replace(/</g, '\\u003c')
  return `<script type="application/ld+json">${json}</script>`
}

function pageHtml(template, route, body) {
  const url = `${SITE_URL}${route.path}`
  let html = template
    .replace(/<title>[\s\S]*?<\/title>/, `<title>${esc(`${route.title} | ${SITE_NAME}`)}</title>`)
    .replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>\s*/g, '')
    .replace(/(<link rel="canonical" href=")[^"]*(")/, `$1${url}$2`)
  html = setMeta(html, 'name', 'description', route.description)
  html = setMeta(html, 'property', 'og:type', route.type === 'article' ? 'article' : 'website')
  html = setMeta(html, 'property', 'og:url', url)
  html = setMeta(html, 'property', 'og:title', route.title)
  html = setMeta(html, 'property', 'og:description', route.description)
  html = setMeta(html, 'name', 'twitter:title', route.title)
  html = setMeta(html, 'name', 'twitter:description', route.description)
  html = html.replace('</head>', `    ${jsonLd(route)}\n  </head>`)
  if (!html.includes('<div id="root"></div>')) {throw new Error('template is missing <div id="root"></div>')}
  return html.replace('<div id="root"></div>', `<div id="root">${body}</div>`)
}

function appendToSitemap(routes) {
  const file = path.join(DIST, 'sitemap.xml')
  const xml = fs.readFileSync(file, 'utf8')
  const entries = routes
    .filter((r) => !xml.includes(`<loc>${SITE_URL}${r.path}</loc>`))
    .map((r) => [
      '  <url>',
      `    <loc>${SITE_URL}${r.path}</loc>`,
      `    <changefreq>${r.type === 'collection' ? 'weekly' : 'monthly'}</changefreq>`,
      `    <priority>${r.type === 'collection' ? '0.8' : '0.7'}</priority>`,
      '  </url>',
    ].join('\n'))
  fs.writeFileSync(file, xml.replace('</urlset>', `  <!-- Generated by scripts/prerender.mjs -->\n${entries.join('\n')}\n\n</urlset>`))
  return entries.length
}

await build({
  root: ROOT,
  logLevel: 'error', // SSR bundle warnings (lazy vs static imports) are expected here
  build: { ssr: 'src/entry-server.jsx', outDir: SSR_OUT, emptyOutDir: true },
})

const { render, contentRoutes } = await import(pathToFileURL(path.join(SSR_OUT, 'entry-server.js')).href)
const template = fs.readFileSync(path.join(DIST, 'index.html'), 'utf8')
const routes = contentRoutes()

for (const route of routes) {
  const body = render(route.path)
  if (!body || body.length < 200) {throw new Error(`prerender of ${route.path} produced no content`)}
  const out = path.join(DIST, `${route.path.replace(/^\//, '')}.html`)
  fs.mkdirSync(path.dirname(out), { recursive: true })
  fs.writeFileSync(out, pageHtml(template, route, body))
}

const added = appendToSitemap(routes)
fs.rmSync(SSR_OUT, { recursive: true, force: true })
console.log(`✓ Prerendered ${routes.length} pages; added ${added} sitemap entries`)
